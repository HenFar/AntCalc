"""Generation of Kira integral families for an antenna, with coverage, reconstruction and comparison checks."""

import dataclasses
from collections import Counter
from itertools import combinations
from pathlib import Path

import sympy as sp

if __package__.partition(".")[0] == "antcalc":
    from .. import integrate_kira as kira
else:
    import integrate_kira as kira

from .cover import choose_cover, first_fit_routing, minimum_cover, order_families
from .kira_yaml import build_family, family_name, render_yaml, write_integralfamilies
from .signatures import (
    candidate_families,
    find_dependent_signatures,
    group_by_signature,
    load_monomials,
)


@dataclasses.dataclass
class GenerationResult:
    """Outcome of generate_families: the families written and how signatures were routed."""

    families: list
    assignment: dict
    n_monomials: int
    n_signatures: int
    dependent_signatures: list
    n_candidates: int
    n_optimal_covers: int
    path: Path


# generation

def generate_families(run, output_path):
    """Generate the minimum set of Kira families covering every denominator signature and write them to yaml."""
    kin = kira.build_kinematics(run.multiplicity)
    monomials = load_monomials(run)
    groups = group_by_signature(monomials)

    dependent = find_dependent_signatures(groups, kin)
    if dependent:
        listing = ", ".join("{" + ", ".join(sorted(map(str, D))) + "}" for D in dependent)
        raise ValueError(f"Dependent denominator signatures cannot share a family: {listing}")

    candidates = candidate_families(kin)
    covers = minimum_cover(groups, candidates)
    cover = choose_cover(covers, groups)
    ordered = order_families(cover, groups)

    names = {tuple(f): family_name(i) for i, f in enumerate(ordered, start=1)}
    families = [build_family(names[tuple(f)], f, run.multiplicity) for f in ordered]
    header = [
        f"Generated by family_generation for {run.antenna_family}{run.multiplicity}{run.loop_order}",
        f"{len(monomials)} monomials, {len(groups)} denominator signatures, {len(ordered)} families",
    ]
    path = write_integralfamilies(render_yaml(families, header), output_path)

    return GenerationResult(
        families=families,
        assignment={D: names[tuple(first_fit_routing(D, ordered))] for D in groups},
        n_monomials=len(monomials),
        n_signatures=len(groups),
        dependent_signatures=dependent,
        n_candidates=len(candidates),
        n_optimal_covers=len(covers),
        path=path,
    )


def prepare_families(run):
    """Generate and check the families for the run's antenna in its Kira work folder, and return their path."""
    if run.substitute_masters:
        raise ValueError(
            "Error! generate_families = 1 requires substitute_masters = 0: the analytic masters in "
            "src/antcalc/masters/ exist only under the hand-written family names."
        )
    name = kira.antenna_name(run)
    path = kira.KIRA_RUN_DIR / f"{name}_families" / "integralfamilies.yaml"
    result = generate_families(run, path)
    cov = check_coverage(run, path)
    if not cov["ok"]:
        raise ValueError(f"Error! The generated integral families do not cover {name}: {cov['error']} (families kept in {path})")
    print(f"Generated {len(result.families)} integral families for {name}: {path}")
    return path


# loading and checks

def _load_families(run, yaml_path):
    """Kira families read from yaml_path through the integrate_kira loader."""
    kin = kira.build_kinematics(run.multiplicity)
    families_list, _ = kira.kira_integral_families(dataclasses.replace(run, families_path=Path(yaml_path)), kin)
    return families_list


def _integrands(run, yaml_path, monomials):
    """Integrands of the given monomials routed through the families in yaml_path."""
    kin = kira.build_kinematics(run.multiplicity)
    return kira.list_to_basis(monomials, _load_families(run, yaml_path), kin)


def check_coverage(run, yaml_path):
    """Route every term of the antenna through the families in yaml_path and report success."""
    try:
        integrands = _integrands(run, yaml_path, load_monomials(run))
    except ValueError as error:
        return {"ok": False, "error": str(error), "n_integrands": 0, "families_used": set()}
    return {
        "ok": True,
        "error": None,
        "n_integrands": len(integrands),
        "families_used": {name for _, (name, _) in integrands},
    }


def _invariant_expressions(kin):
    """Every invariant (and q2) as its sum of s_ij over the pairs it contains."""
    pair_symbols = [sp.Symbol(f"s{i}{j}") for i, j in combinations(range(1, kin.multiplicity + 1), 2)]
    return {
        invariant: sum(sym for sym, bit in zip(pair_symbols, vector) if bit)
        for invariant, vector in kin.invariant_vectors.items()
    }


def check_reconstruction(run, yaml_path):
    """True if the generated integrands, rebuilt in s_ij, reproduce the antenna exactly."""
    kin = kira.build_kinematics(run.multiplicity)
    exprs = _invariant_expressions(kin)
    families = dict(_load_families(run, yaml_path))
    monomials = load_monomials(run)
    integrands = kira.list_to_basis(monomials, list(families.items()), kin)

    def term(coeff, factors):
        pairs = sp.sympify(coeff).subs(kira.q2, exprs[kira.q2])
        return pairs * sp.Mul(*(exprs[inv] ** power for inv, power in factors.items()))

    rebuilt = sum(term(coeff, dict(zip(families[name], powers))) for coeff, (name, powers) in integrands)
    original = sum(term(coeff, factors) for coeff, factors in monomials)
    return sp.cancel(sp.together(rebuilt - original)) == 0


def _kira_indices(powers):
    """Kira indices of an integrand: the negated monomial powers, as in term_to_form."""
    return tuple(-p for p in powers)


def _dots_and_s(powers):
    """Kira dots and numerator power of an integrand, as in integral_seeds."""
    indices = _kira_indices(powers)
    r = sum(i for i in indices if i > 0)
    s = -sum(i for i in indices if i < 0)
    return r - sum(1 for i in indices if i > 0), s


def _side_summary(prefix, integrands):
    """Distinct integrals, max r and s, and per-family distinct counts of one side."""
    distinct = {(name, tuple(powers)) for _, (name, powers) in integrands}
    per_family = Counter(name for name, _ in distinct)
    return {
        f"{prefix}_total": len(integrands),
        f"{prefix}_used": set(per_family),
        f"{prefix}_terms": dict(Counter(name for _, (name, _) in integrands)),
        f"{prefix}_distinct": len(distinct),
        f"{prefix}_max_dots": max((_dots_and_s(p)[0] for _, p in distinct), default=0),
        f"{prefix}_max_s": max((_dots_and_s(p)[1] for _, p in distinct), default=0),
        f"{prefix}_family_distinct": dict(per_family),
    }


def compare_with_handwritten(run, generated_path, handwritten_path):
    """Compare integrand counts, distinct integrals and family usage of the handwritten and generated yaml."""
    monomials = load_monomials(run)
    hand = _integrands(run, handwritten_path, monomials)
    gen = _integrands(run, generated_path, monomials)
    hand_families = _load_families(run, handwritten_path)
    gen_families = _load_families(run, generated_path)
    return _side_summary("hand", hand) | _side_summary("gen", gen) | {
        "hand_families": len(hand_families),
        "gen_families": len(gen_families),
    }
